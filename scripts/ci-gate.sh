#!/usr/bin/env bash
# Enterprise readiness CI gate.
#
# Runs the module-index check, backend typecheck (with a known-issues
# baseline so we don't break on pre-existing errors that are tracked
# separately), key vitest specs, and a healthz smoke.
#
# Usage:  scripts/ci-gate.sh
# Env:    BACKEND_DIR (default apps/nestjs-backend)
#         HEALTH_URL  (default http://127.0.0.1:3000/healthz)
#         BASELINE    (default scripts/ci-baseline.json)

set -uo pipefail

cd "$(dirname "$0")/.."
ROOT="$(pwd)"
BACKEND_DIR="${BACKEND_DIR:-apps/nestjs-backend}"
HEALTH_URL="${HEALTH_URL:-http://127.0.0.1:3000/healthz}"
BASELINE="${BASELINE:-scripts/ci-baseline.json}"

step() {
  printf '\n\033[1;36m== %s ==\033[0m\n' "$1"
}

fail() {
  printf '\033[1;31m✗ %s\033[0m\n' "$1" >&2
  exit 1
}

pass() {
  printf '\033[1;32m✓ %s\033[0m\n' "$1"
}

# 1. Module-index sync — keeps the autogenerated `index.ts` files in lockstep
# with the actual source exports.
step "module-index sync"
if pnpm check:module-index; then
  pass "module-index is in sync"
else
  fail "module-index drift detected — run 'pnpm generate:module-index'"
fi

# 2. Backend typecheck — fails when new production (non-test) TS errors
# appear that aren't already in the baseline.
step "backend typecheck"
TSC_LOG="$(cd "$BACKEND_DIR" && pnpm exec tsc --noEmit 2>&1 || true)"
PROD_ERR="$(printf '%s\n' "$TSC_LOG" | grep -E "error TS" \
  | rg -v "\\.spec\\.ts|\\.e2e-spec\\.ts|\\.test\\.ts" || true)"
TOTAL_ERR="$(printf '%s\n' "$TSC_LOG" | grep -c -E "error TS" 2>/dev/null || true)"
TOTAL_ERR="${TOTAL_ERR:-0}"

# Subtract baseline entries by file basename:line prefix (relative to backend).
BASELINE_PAIRS="$(
  if [ -f "$BASELINE" ] && command -v python3 >/dev/null; then
    python3 -c "
import json, os
data = json.load(open('$BASELINE'))
for e in data.get('productionTypeErrors', []):
    base = os.path.basename(e['file'])
    print(f\"{base}:{e['line']}\")
" 2>/dev/null
  fi
)"

NEW_PROD_ERR=""
while IFS= read -r line; do
  [ -z "$line" ] && continue
  # Strip the leading path; match `(line,col)` after the file basename.
  base="$(printf '%s' "$line" | sed -E 's@.*/([^/(]+\.ts)\(([0-9]+),.*@\1:\2@')"
  is_baseline=0
  for b in $BASELINE_PAIRS; do
    if [ "$b" = "$base" ]; then
      is_baseline=1
      break
    fi
  done
  if [ "$is_baseline" -eq 0 ]; then
    NEW_PROD_ERR="${NEW_PROD_ERR}${line}"$'\n'
  fi
done <<EOF
$PROD_ERR
EOF
NEW_PROD_COUNT="$(printf '%s' "$NEW_PROD_ERR" | grep -c "error TS" 2>/dev/null || echo 0)"
NEW_PROD_COUNT="$(printf "%s" "$NEW_PROD_COUNT" | tr -d "\n" | tr -d " ")"
if [ "$NEW_PROD_COUNT" -gt 0 ]; then
  printf '%s\n' "$NEW_PROD_ERR" >&2
  fail "backend typecheck failed — $NEW_PROD_COUNT new production errors (total $TOTAL_ERR)"
fi
pass "no new production type errors (total: $TOTAL_ERR; baseline subtracted)"

# 3. Key vitest specs — runs the enterprise-readiness slices.
step "key vitest specs"
if (cd "$BACKEND_DIR" && pnpm exec vitest run \
    src/features/agent-orchestrator \
    src/features/permission-matrix \
    src/features/auth/turnstile \
    src/features/view/open-api \
    --silent); then
  pass "key vitest specs passed"
else
  fail "key vitest specs failed"
fi

# 4. Enterprise readiness e2e smoke — exercises all the new admin surface
# endpoints (R-INFRA-4/5) and asserts 80/80 capabilities enabled.
step "enterprise-readiness e2e"
if [ -x scripts/e2e-enterprise-admin-surface.sh ]; then
  if BASE_URL="${BASE_URL:-http://127.0.0.1:3000}"       TEABLE_ADMIN_TOKEN="${TEABLE_ADMIN_TOKEN:-test-token}"       TEABLE_SMOKE_EMAIL="${TEABLE_SMOKE_EMAIL:-hello@teable.io}"       TEABLE_SMOKE_PASSWORD="${TEABLE_SMOKE_PASSWORD:-password123}"       scripts/e2e-enterprise-admin-surface.sh; then
    pass "enterprise-readiness e2e reached 80/80 capabilities"
  else
    fail "enterprise-readiness e2e failed — check /tmp/teable-backend.log"
  fi
else
  printf '\033[1;33m⚠ e2e-enterprise-admin-surface.sh missing (skipping)\033[0m\n'
fi

# 5. Healthz smoke — only if the URL is reachable. We don't fail the gate when
# the dev server isn't running locally; CI will spin one up before invoking.
step "healthz smoke ($HEALTH_URL)"
if curl -sS -o /dev/null -w '%{http_code}' --max-time 5 "$HEALTH_URL" 2>/dev/null \
    | grep -q '^200$'; then
  pass "healthz returns 200"
else
  printf '\033[1;33m⚠ healthz unreachable (skipping)\033[0m\n'
fi

printf '\n\033[1;32mAll gates passed.\033[0m\n'

# 6. Whitespace sanity — catches accidental CRLF / trailing whitespace in the
# working tree diff. Cheap, fast, catches the easy regressions.
step "git diff whitespace"
if git diff --check HEAD 2>/dev/null || git diff --check 2>/dev/null; then
  pass "no whitespace issues in working diff"
else
  fail "git diff --check reported whitespace problems"
fi
